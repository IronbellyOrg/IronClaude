"""
Install the shared Claude Code user setup: rules, output styles, settings
defaults, and Orca's bundled skills.

- Rules go to ~/.claude/rules/<group>/. Claude Code loads every file under
  ~/.claude/rules/ into every session, so each shipped group is also listed
  in settings.json ``claudeMdExcludes`` by exact path; templates read them
  on demand instead.
- Output styles go to ~/.claude/output-styles/.
- Settings defaults only fill keys the user has not set, so a person's own
  choices are never overwritten. Nested maps (env, plugins, marketplaces,
  per-model settings) are filled entry by entry.
- Orca skills are generated by the Orca CLI for its own version, so they are
  requested from Orca when it is installed rather than shipped here.
- Plugins listed in the defaults are installed with the `claude` CLI, since
  enabling a plugin in settings.json does not download it.
- Third-party plugins IronClaude enables by default come from its own
  marketplace: the defaults' ``ironclaudeMarketplace`` catalog is written to
  ~/.claude/ironclaude-marketplace/ on every run, and each entry pins a commit,
  so a plugin changes only when a release changes the pin.
"""

import json
import os
import shutil
import subprocess
import time
from pathlib import Path
from typing import List, Tuple

from .install_hooks import _atomic_write_json, _backup_path
from .install_keep import backup_if_differs, same_content

_RULE_GROUPS = ("core", "contextual", "prompts")
_ORCA_SKILLS = ("computer-use", "orca-cli", "orchestration")
_ORCA_CLIS = ("orca-ide", "orca")
# `superclaude install` runs under a 60-second limit in Coder workspaces. The
# Orca and plugin steps download over the network, so together they get a
# bounded share of that; anything unfinished is reported, never fatal.
_ORCA_TIMEOUT = 25
_NETWORK_BUDGET = 30
_NESTED_KEYS = ("env", "enabledPlugins", "extraKnownMarketplaces", "modelSettings")
# Default plugins whose id changed: a user's `false` under the old id carries
# over to the new one, so an opt-out survives the rename.
_RENAMED_PLUGINS = {"ponytail@ironclaude": "ponytail@ponytail"}
# The pinned catalog is read by install_plugins and never copied into settings.
_CATALOG_KEY = "ironclaudeMarketplace"
_CATALOG_DIR = Path(".claude") / "ironclaude-marketplace"
# `claude plugin update` clones GitHub sources over SSH, which fails without a
# key; these git settings make that one command clone over HTTPS instead.
_HTTPS_GITHUB = {
    "GIT_CONFIG_COUNT": "1",
    "GIT_CONFIG_KEY_0": "url.https://github.com/.insteadOf",
    "GIT_CONFIG_VALUE_0": "git@github.com:",
}


def _package_dir(name: str) -> Path:
    """Locate src/superclaude/<name> for editable and wheel installs."""
    package_root = Path(__file__).resolve().parent.parent
    editable = package_root / name
    if editable.is_dir():
        return editable
    wheel = package_root / "_src" / "superclaude" / name
    return wheel if wheel.is_dir() else editable


def _copy_tree(
    source: Path,
    dest: Path,
    force: bool,
    stale: List[str] | None = None,
    backups: List[str] | None = None,
) -> Tuple[int, int, List[str]]:
    """Copy ``source`` into ``dest``.

    Without ``force`` an existing file is kept; a kept file that differs from
    the shipped copy is appended to ``stale``. With ``force`` a differing file
    is saved aside first (path appended to ``backups``); if that save fails the
    file is left untouched and reported in the failures.
    """
    copied = skipped = 0
    failed: List[str] = []
    for src in sorted(source.rglob("*")):
        if not src.is_file() or "__pycache__" in src.parts or src.name == ".DS_Store":
            continue
        target = dest / src.relative_to(source)
        if target.exists() and not force:
            skipped += 1
            if stale is not None and not same_content(src, target):
                stale.append(str(src.relative_to(source)))
            continue
        try:
            if target.exists():
                backup = backup_if_differs(src, target)
                if backup is not None and backups is not None:
                    backups.append(str(backup))
        except OSError as exc:
            failed.append(
                f"{target}: could not save a copy first, left untouched ({exc})"
            )
            continue
        try:
            target.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(src, target)
            copied += 1
        except OSError as exc:
            failed.append(f"{target}: {exc}")
    return copied, skipped, failed


def _keep_notes(label: str, stale: List[str], backups: List[str]) -> str:
    """Report kept files that differ from this version and forced backups."""
    notes = ""
    if stale:
        notes += (
            f"\n⚠️  {len(stale)} kept {label}(s) differ from this version and "
            "were NOT updated (run with --force or `superclaude update` to refresh; "
            "a differing file is saved as <name>.bak.<time> first): " + ", ".join(stale)
        )
    if backups:
        notes += (
            f"\n💾 Saved {len(backups)} changed {label}(s) before overwriting: "
            + ", ".join(backups)
        )
    return notes


def _load_settings(path: Path) -> Tuple[dict | None, str]:
    if not path.exists():
        return {}, ""
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as exc:
        return None, f"❌ {path} is unreadable or malformed; left untouched ({exc})"
    if not isinstance(data, dict):
        return None, f"❌ {path} is not a JSON object; left untouched"
    return data, ""


def _write_settings(path: Path, data: dict) -> str:
    """Back up and atomically replace settings.json; returns the backup path."""
    path.parent.mkdir(parents=True, exist_ok=True)
    backup = ""
    if path.exists():
        backup_file = _backup_path(path)
        shutil.copy2(path, backup_file)
        backup = str(backup_file)
    _atomic_write_json(path, data)
    return backup


def install_rules(home: Path | None = None, force: bool = False) -> Tuple[bool, str]:
    home = Path.home() if home is None else Path(home)
    source = _package_dir("rules")
    if not source.is_dir():
        return False, f"❌ Rules source not found: {source}"
    rules_dir = home / ".claude" / "rules"
    stale: List[str] = []
    backups: List[str] = []
    copied, skipped, failed = _copy_tree(source, rules_dir, force, stale, backups)

    settings_path = home / ".claude" / "settings.json"
    settings, error = _load_settings(settings_path)
    if settings is None:
        return False, error
    excludes = settings.get("claudeMdExcludes", [])
    if not isinstance(excludes, list):
        return (
            False,
            f"❌ {settings_path} claudeMdExcludes is not a list; left untouched",
        )
    wanted = [str(rules_dir / group) + "/**" for group in _RULE_GROUPS]
    missing = [pattern for pattern in wanted if pattern not in excludes]
    if missing:
        settings["claudeMdExcludes"] = excludes + missing
        _write_settings(settings_path, settings)

    message = f"✅ Rules: {copied} installed, {skipped} kept, in {rules_dir} (never auto-loaded)"
    message += _keep_notes("rule file", stale, backups)
    if failed:
        message += "\n❌ " + "\n❌ ".join(failed)
    return not failed, message


def install_output_styles(
    home: Path | None = None, force: bool = False
) -> Tuple[bool, str]:
    home = Path.home() if home is None else Path(home)
    source = _package_dir("output-styles")
    if not source.is_dir():
        return False, f"❌ Output styles source not found: {source}"
    dest = home / ".claude" / "output-styles"
    stale: List[str] = []
    backups: List[str] = []
    copied, skipped, failed = _copy_tree(source, dest, force, stale, backups)
    message = f"✅ Output styles: {copied} installed, {skipped} kept, in {dest}"
    message += _keep_notes("output style", stale, backups)
    if failed:
        message += "\n❌ " + "\n❌ ".join(failed)
    return not failed, message


def apply_settings_defaults(home: Path | None = None) -> Tuple[bool, str]:
    home = Path.home() if home is None else Path(home)
    defaults_path = Path(__file__).resolve().parent / "user_settings_defaults.json"
    try:
        defaults = json.loads(defaults_path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as exc:
        return False, f"❌ Settings defaults unreadable at {defaults_path}: {exc}"

    settings_path = home / ".claude" / "settings.json"
    settings, error = _load_settings(settings_path)
    if settings is None:
        return False, error

    added: List[str] = []
    for key, value in defaults.items():
        if key == _CATALOG_KEY:
            continue
        current = settings.get(key)
        if key in _NESTED_KEYS and isinstance(value, dict):
            if current is None:
                current = settings[key] = {}
            if not isinstance(current, dict):
                continue  # A user value of another shape is theirs; keep it.
            for name, entry in value.items():
                if name not in current:
                    old_id = (
                        _RENAMED_PLUGINS.get(name) if key == "enabledPlugins" else None
                    )
                    current[name] = False if current.get(old_id) is False else entry
                    added.append(f"{key}.{name}")
        elif key not in settings:
            settings[key] = value
            added.append(key)

    if not added:
        return True, "✅ Settings defaults: already present"
    backup = _write_settings(settings_path, settings)
    message = f"✅ Settings defaults: added {len(added)} ({', '.join(added)})"
    if backup:
        message += f"\n💾 Backup: {backup}"
    return True, message


def _find_orca() -> str | None:
    """Return an Orca CLI that answers `skills list`, never another program.

    On Linux a bare `orca` outside Orca's own terminals is usually the GNOME
    screen reader, so each candidate must prove it is Orca before use.
    """
    for name in _ORCA_CLIS:
        path = shutil.which(name)
        if not path:
            continue
        try:
            probe = subprocess.run(
                [path, "skills", "list", "--json"],
                capture_output=True,
                text=True,
                timeout=10,
                stdin=subprocess.DEVNULL,
            )
            topics = json.loads(probe.stdout).get("topics", [])
        except (OSError, subprocess.SubprocessError, ValueError, AttributeError):
            continue
        if probe.returncode == 0 and any(t.get("name") == "orca-cli" for t in topics):
            return path
    return None


def _orca_timeout(deadline: float | None) -> float:
    if deadline is None:
        return _ORCA_TIMEOUT
    return max(1.0, min(_ORCA_TIMEOUT, deadline - time.monotonic()))


def install_orca_skills(
    home: Path | None = None, deadline: float | None = None, force: bool = False
) -> Tuple[bool, str]:
    """Request Orca's safe guide install/refresh; never force-replace edited guides."""
    home = Path.home() if home is None else Path(home)
    skills_dir = home / ".claude" / "skills"
    if not force and all(
        (skills_dir / name / "SKILL.md").exists() for name in _ORCA_SKILLS
    ):
        return True, "✅ Orca skills: already installed"
    orca = _find_orca()
    if orca is None:
        return True, "⏭️  Orca skills: Orca CLI not found; skipped"
    command = [orca, "skills", "install", "--agent", "claude-code"]
    for name in _ORCA_SKILLS:
        command += ["--skill", name]
    try:
        result = subprocess.run(
            command,
            capture_output=True,
            text=True,
            timeout=_orca_timeout(deadline),
            stdin=subprocess.DEVNULL,
        )
    except (OSError, subprocess.SubprocessError) as exc:
        message = (
            f"⚠️  Orca skills: not installed ({exc}); rerun `{orca} skills install`"
        )
        for stream in (getattr(exc, "stdout", None), getattr(exc, "stderr", None)):
            if isinstance(stream, bytes):
                stream = stream.decode("utf-8", errors="replace")
            if stream and stream.strip():
                message += f"\n{stream.strip()}"
        return True, message
    installed = [n for n in _ORCA_SKILLS if (skills_dir / n / "SKILL.md").exists()]
    if result.returncode != 0 or len(installed) != len(_ORCA_SKILLS):
        message = (
            f"⚠️  Orca skills: install request failed or incomplete "
            f"({len(installed)}/{len(_ORCA_SKILLS)} files present); "
            f"rerun `{orca} skills install`"
        )
    else:
        message = (
            "✅ Orca skills: install request completed (see Orca output for any skips)"
        )
    details = "\n".join(
        part.strip() for part in (result.stdout, result.stderr) if part.strip()
    )
    return True, "\n".join(part for part in (message, details) if part)


def _read_json(path: Path) -> dict:
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return {}
    return data if isinstance(data, dict) else {}


def _write_catalog(home: Path, catalog: dict) -> bool:
    """Write the pinned marketplace file; True when its content changed."""
    path = home / _CATALOG_DIR / ".claude-plugin" / "marketplace.json"
    if _read_json(path) == catalog:
        return False
    path.parent.mkdir(parents=True, exist_ok=True)
    _atomic_write_json(path, catalog)
    return True


def _is_our_catalog(entry: object, home: Path) -> bool:
    """True only when a registered marketplace entry is IronClaude's catalog."""
    source = entry.get("source") if isinstance(entry, dict) else None
    if not isinstance(source, dict) or source.get("source") != "directory":
        return False
    path = source.get("path")
    if not isinstance(path, str) or not Path(path).is_absolute():
        return False
    try:
        return Path(path).resolve() == (home / _CATALOG_DIR).resolve()
    except (OSError, RuntimeError, ValueError):  # a symlink loop or a NUL byte
        return False  # not provably ours, so refused like another source


def install_plugins(
    home: Path | None = None, deadline: float | None = None
) -> Tuple[bool, str]:
    """Download the default plugins the user has not disabled; never fatal.

    Plugins from the IronClaude catalog are installed at their pinned commit,
    and one installed at another commit is updated to the pin.
    """
    home = Path.home() if home is None else Path(home)
    claude = shutil.which("claude")
    if claude is None:
        return True, "⏭️  Plugins: claude CLI not found; skipped"
    deadline = time.monotonic() + _NETWORK_BUDGET if deadline is None else deadline
    defaults = _read_json(
        Path(__file__).resolve().parent / "user_settings_defaults.json"
    )
    settings = _read_json(home / ".claude" / "settings.json")
    enabled = settings.get("enabledPlugins", {})
    enabled = enabled if isinstance(enabled, dict) else {}
    wanted = [p for p in defaults.get("enabledPlugins", {}) if enabled.get(p) is True]
    plugins_dir = home / ".claude" / "plugins"
    known = _read_json(plugins_dir / "known_marketplaces.json")
    records = _read_json(plugins_dir / "installed_plugins.json").get("plugins", {})
    records = records if isinstance(records, dict) else {}
    # Only user-scope copies count: every command below acts at user scope, and
    # a project-scope copy (even one at the pin) covers a single project.
    installed = {
        p: [e for e in r if isinstance(e, dict) and e.get("scope", "user") == "user"]
        for p, r in records.items()
        if isinstance(r, list)
    }
    installed = {p: r for p, r in installed.items() if r}
    catalog = defaults.get(_CATALOG_KEY, {})
    pinned = {
        f"{entry['name']}@{catalog['name']}": entry["source"].get("sha")
        for entry in catalog.get("plugins", [])
    }
    stale = [
        p
        for p in wanted
        if p in pinned
        and p in installed
        and pinned[p]
        not in {e.get("gitCommitSha") for e in installed[p] if isinstance(e, dict)}
    ]

    # (name in the report, marketplace it depends on, arguments)
    commands: List[Tuple[str, str, List[str]]] = []
    failed: List[str] = []
    if any(p in pinned for p in wanted):
        name = catalog["name"]
        refused = ""
        try:
            changed = _write_catalog(home, catalog)
        except OSError:
            refused = "catalog not written"
        else:
            if name in known and not _is_our_catalog(known[name], home):
                # Never install a pinned plugin through a marketplace that only
                # shares the name; the user's own registration is left alone.
                refused = (
                    "registered from another source, so its plugins were not "
                    "installed or updated; run `claude plugin marketplace add "
                    f"{home / _CATALOG_DIR}` to use IronClaude's pinned catalog"
                )
            elif name not in known:
                add = ["plugin", "marketplace", "add", str(home / _CATALOG_DIR)]
                commands.append((name, name, add))
                known[name] = {}
            elif changed or stale:
                update = ["plugin", "marketplace", "update", name]
                commands.append((name, name, update))
        if refused:
            failed.append(f"{name} ({refused})")
            wanted = [p for p in wanted if p not in pinned]
            stale = []
    for plugin in wanted:
        market = plugin.split("@", 1)[1]
        source = (
            defaults.get("extraKnownMarketplaces", {}).get(market, {}).get("source", {})
        )
        if market not in known and source.get("repo"):
            add = ["plugin", "marketplace", "add", source["repo"]]
            commands.append((source["repo"], market, add))
            known[market] = source
    commands += [
        (p, p.split("@", 1)[1], ["plugin", "install", p, "--scope", "user", "-y"])
        for p in wanted
        if p not in installed
    ]
    commands += [
        (p, p.split("@", 1)[1], ["plugin", "update", p, "--scope", "user"])
        for p in stale
    ]
    if not commands and not failed:
        return True, "✅ Plugins: already installed"

    broken = set()  # marketplaces whose add or update failed in this run
    for name, market, args in commands:
        remaining = deadline - time.monotonic()
        if remaining < 2:
            failed.append(f"{name} (time limit)")
            continue
        if market in broken:
            failed.append(f"{name} (marketplace {market} unavailable)")
            continue
        # Every command acts on the profile checked above (home/.claude), where
        # this module writes its files, never one CLAUDE_CONFIG_DIR names.
        env = {k: v for k, v in os.environ.items() if k != "CLAUDE_CONFIG_DIR"}
        env["HOME"] = str(home)
        if args[1] == "update":
            env.update(_HTTPS_GITHUB)
        try:
            result = subprocess.run(
                [claude, *args],
                capture_output=True,
                text=True,
                timeout=remaining,
                stdin=subprocess.DEVNULL,
                env=env,
            )
            ok = result.returncode == 0
        except (OSError, subprocess.SubprocessError):
            ok = False
        if not ok:
            failed.append(name)
            if args[1] == "marketplace":
                broken.add(market)
    if failed:
        return True, (
            f"⚠️  Plugins: not installed: {', '.join(failed)}; "
            "rerun `superclaude install` to retry"
        )
    return True, f"✅ Plugins: installed {', '.join(wanted)}"


def install_user_setup(force: bool = False) -> Tuple[bool, str]:
    """Run every user-setup step; returns combined success and messages."""
    deadline = time.monotonic() + _NETWORK_BUDGET
    results = [
        install_rules(force=force),
        install_output_styles(force=force),
        apply_settings_defaults(),
        install_orca_skills(deadline=deadline, force=force),
        install_plugins(deadline=deadline),
    ]
    return all(ok for ok, _ in results), "\n".join(msg for _, msg in results)
