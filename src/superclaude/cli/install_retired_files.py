"""Retire step: remove installed commands, skills and agents a release stopped shipping.

Runs at the end of ``superclaude install`` and ``superclaude update`` and never
changes their exit code. The installers copy what a release ships but never delete
what a release stops shipping, so an upgraded workspace keeps dead commands such as
``/sc:roadmap``. This step removes them, but only what IronClaude can prove it wrote:

- a command or agent file is removed only when its sha256 equals the file as shipped
  at an earlier release tag (``install_retired_data``, generated by
  ``scripts/gen_retired_install_data.py``);
- a skill is a folder and is removed only when every entry in it is a shipped file
  with a matching sha256; one extra, edited, linked or unreadable entry keeps the
  whole folder.

Everything else is kept and reported on one line with the reason and the exact
command that removes it. Only names in the generated data are looked at, only inside
``~/.claude/commands/sc/`` (or the ``--target`` folder the commands were installed
to), ``~/.claude/skills/`` and ``~/.claude/agents/``. A name the current release
ships is never touched. A failure on one item is printed and never raised.
"""

from __future__ import annotations

import hashlib
import os
import re
import shlex
import stat
from pathlib import Path
from typing import NamedTuple

import click

from . import install_retired_data as data

_NAME = re.compile(r"^[A-Za-z0-9][A-Za-z0-9._-]*$")
_PART = re.compile(r"^[A-Za-z0-9_][A-Za-z0-9._-]*$")
_SHOWN = 3  # how many differing paths a kept line names


class Finding(NamedTuple):
    """verdict: absent | remove | keep. ``files`` is only set for a removable skill."""

    kind: str
    name: str
    verdict: str
    reason: str
    path: Path
    files: tuple = ()


def _sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def _is_regular(path: Path) -> bool:
    try:
        return stat.S_ISREG(path.lstat().st_mode)
    except OSError:
        return False


def _classify_file(kind: str, name: str, path: Path, hashes: tuple) -> Finding:
    if not os.path.lexists(path):
        return Finding(kind, name, "absent", "", path)
    if not _is_regular(path):
        return Finding(kind, name, "keep", "it is a link or a folder, not a file", path)
    try:
        digest = _sha256(path)
    except OSError as exc:
        return Finding(
            kind, name, "keep", f"it could not be read ({type(exc).__name__})", path
        )
    if digest in hashes:
        return Finding(kind, name, "remove", "unchanged since it was installed", path)
    return Finding(
        kind,
        name,
        "keep",
        "its content differs from every copy IronClaude shipped "
        "(you edited it, or it came from another source)",
        path,
    )


def _skill_dirs(files: dict) -> set[str]:
    dirs: set[str] = set()
    for rel in files:
        parent = Path(rel).parent
        while str(parent) != ".":
            dirs.add(parent.as_posix())
            parent = parent.parent
    return dirs


def _classify_skill(name: str, folder: Path, files: dict) -> Finding:
    if not os.path.lexists(folder):
        return Finding("skill", name, "absent", "", folder)
    if folder.is_symlink() or not folder.is_dir():
        return Finding("skill", name, "keep", "it is a link, not a folder", folder)
    known_dirs = _skill_dirs(files)
    problems: list[str] = []
    provable: list[Path] = []
    unreadable: list[str] = []

    def _onerror(exc: OSError) -> None:
        unreadable.append(type(exc).__name__)

    for root, dirnames, filenames in os.walk(folder, onerror=_onerror):
        base = Path(root)
        for sub in list(dirnames):
            rel = (base / sub).relative_to(folder).as_posix()
            if (base / sub).is_symlink() or rel not in known_dirs:
                problems.append(rel + "/")
                dirnames.remove(sub)
        for fname in filenames:
            path = base / fname
            rel = path.relative_to(folder).as_posix()
            hashes = files.get(rel)
            if hashes is None or not _is_regular(path):
                problems.append(rel)
                continue
            try:
                same = _sha256(path) in hashes
            except OSError:
                problems.append(rel)
                continue
            if same:
                provable.append(path)
            else:
                problems.append(rel)
    if unreadable:
        return Finding(
            "skill",
            name,
            "keep",
            f"the folder could not be read completely ({unreadable[0]})",
            folder,
        )
    if problems:
        problems.sort()
        shown = ", ".join(problems[:_SHOWN])
        more = f" and {len(problems) - _SHOWN} more" if len(problems) > _SHOWN else ""
        return Finding(
            "skill",
            name,
            "keep",
            f"{len(problems)} path(s) in it were added or changed after IronClaude "
            f"installed it ({shown}{more})",
            folder,
        )
    return Finding(
        "skill",
        name,
        "remove",
        "unchanged since it was installed",
        folder,
        tuple(provable),
    )


def _shipped_names() -> dict[str, set[str]]:
    """Names this release ships; a name on the retired list that is also here is skipped."""
    from .install_agents import list_available_agents
    from .install_commands import list_available_commands
    from .install_skill import list_available_skills

    return {
        "command": set(list_available_commands()),
        "agent": set(list_available_agents()),
        "skill": set(list_available_skills()),
    }


def _folders(commands_dir: Path | None) -> dict[str, Path]:
    claude = Path.home() / ".claude"
    return {
        "command": commands_dir or claude / "commands" / "sc",
        "skill": claude / "skills",
        "agent": claude / "agents",
    }


def _roster(shipped: dict[str, set[str]]) -> list[tuple[str, str]]:
    """(kind, name) of every listed item that is safe to look at and not shipped now."""
    roster = [("command", n) for n in data.RETIRED_COMMANDS]
    roster += [("agent", n) for n in data.RETIRED_AGENTS]
    roster += [
        ("skill", n)
        for n, files in data.RETIRED_SKILLS.items()
        if all(_PART.match(p) for rel in files for p in rel.split("/"))
    ]
    return [(k, n) for k, n in roster if _NAME.match(n) and n not in shipped[k]]


def _classify_one(kind: str, name: str, commands_dir: Path | None) -> Finding:
    folder = _folders(commands_dir)[kind]
    if kind == "skill":
        return _classify_skill(name, folder / name, data.RETIRED_SKILLS[name])
    hashes = (data.RETIRED_COMMANDS if kind == "command" else data.RETIRED_AGENTS)[name]
    return _classify_file(kind, name, folder / f"{name}.md", hashes)


def classify_retired_files(commands_dir: Path | None = None) -> list[Finding]:
    """Read the three folders once; no writes. Findings for absent names are included."""
    return [
        _classify_one(kind, name, commands_dir)
        for kind, name in _roster(_shipped_names())
    ]


def _label(finding: Finding) -> str:
    if finding.kind == "command":
        return f"/sc:{finding.name}"
    return f"{finding.kind} {finding.name}"


def _removal_command(finding: Finding) -> str:
    verb = "rm -r" if finding.kind == "skill" else "rm"
    return f"{verb} {shlex.quote(str(finding.path))}"


def _still_proven(path: Path, hashes: tuple) -> bool:
    try:
        return _is_regular(path) and _sha256(path) in hashes
    except OSError:
        return False


def _remove(finding: Finding, commands_dir: Path | None) -> str:
    """Re-check the proof right before deleting; returns removed | kept | failed."""
    fresh = _classify_one(finding.kind, finding.name, commands_dir)
    if fresh.verdict != "remove":
        return "kept"
    try:
        if fresh.kind == "skill":
            files = data.RETIRED_SKILLS[fresh.name]
            for path in fresh.files:
                # Proof again for every file, right before it goes: the classification
                # above ran before the first delete, and a file may change meanwhile.
                rel = path.relative_to(fresh.path).as_posix()
                if not _still_proven(path, files[rel]):
                    click.echo(
                        f"   Kept the rest of {_label(fresh)}: {rel} changed while "
                        "this step ran (the files removed before it were unchanged). "
                        f"Remove it yourself with `{_removal_command(fresh)}` if "
                        "you want it gone."
                    )
                    return "kept"
                path.unlink()
            for root, _dirs, _files in os.walk(fresh.path, topdown=False):
                os.rmdir(root)
        else:
            fresh.path.unlink()
    except OSError as exc:
        click.echo(
            f"   ⚠️  Could not remove {_label(fresh)} ({type(exc).__name__}); "
            f"remove it yourself with `{_removal_command(fresh)}` if you want it gone."
        )
        return "failed"
    return "removed"


def run_retire_files_step(commands_dir: Path | None = None) -> dict[str, str]:
    """Retire stale files. Prints one line per item; returns ``kind:name`` -> outcome.

    ``commands_dir`` is the folder the commands were installed to (``--target``).
    Callers wrap this in ``try/except``: no outcome may change the install exit code.
    """
    findings = [
        f for f in classify_retired_files(commands_dir) if f.verdict != "absent"
    ]
    outcomes: dict[str, str] = {}
    if not findings:
        click.echo("   No retired commands, skills or agents present.")
        return outcomes
    removed_any = False
    for finding in findings:
        key = f"{finding.kind}:{finding.name}"
        if finding.verdict == "keep":
            click.echo(
                f"   Kept {_label(finding)}: {finding.reason}. This release no "
                f"longer ships it, so it is dead weight. Remove it yourself with "
                f"`{_removal_command(finding)}`"
            )
            outcomes[key] = "kept"
            continue
        outcome = _remove(finding, commands_dir)
        outcomes[key] = outcome
        if outcome == "removed":
            removed_any = True
            click.echo(
                f"   Removed {_label(finding)} (this release no longer ships it; "
                f"{finding.reason})"
            )
        elif outcome == "kept":
            click.echo(f"   Kept {_label(finding)}: it changed while this step ran")
    if removed_any:
        click.echo(
            "   Restart running Claude Code sessions so the removed commands "
            "and skills disappear."
        )
    return outcomes
