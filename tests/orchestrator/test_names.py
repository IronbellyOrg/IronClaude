"""The naming rule (design 5.12): nothing a person reads names the agent or the model."""

from __future__ import annotations

import pytest

from superclaude.cli.orchestrator.names import (
    ALLOWED_LINES,
    ALLOWED_NAMES,
    DENY_PATTERNS,
    QUOTED_HEADINGS,
    names_check,
)

TRAILER = "Co-Authored-By: Claude Code <noreply@anthropic.com>"


def kinds(text: str) -> list[str]:
    return [h.kind for h in names_check(text)]


@pytest.mark.parametrize(
    "text",
    [
        "Worker tier: claude-gw-tier2",
        "The model was claude-opus-4-1 for this one.",
        "ran on gpt-4o-mini",
        "ran on gemini-2.5-pro",
        "CLAUDE-GW-TIER2 appeared",
    ],
)
def test_a_model_identifier_in_plain_text_fails(text: str) -> None:
    assert kinds(text) == ["model_id"]


@pytest.mark.parametrize(
    "text",
    [
        "Claude wrote this part.",
        "done with the help of Anthropic's assistant",
        "asked ChatGPT about it",
        "written by OpenAI tools",
        "suggested by Copilot",
        "Gemini drafted the plan",
        "GPT-5 fixed it",
        "Opus 5 reviewed it",
        "Sonnet 4 reviewed it",
        "Claude Code opened this pull request",
    ],
)
def test_an_agent_product_name_in_plain_text_fails(text: str) -> None:
    assert "agent_name" in kinds(text)


def test_a_generated_with_line_for_an_agent_fails() -> None:
    assert kinds("Fixes it.\n\n\U0001f916 Generated with an AI assistant") == [
        "attribution"
    ]
    assert kinds("Generated by the coding agent") == ["attribution"]
    assert kinds("Co-Authored-By: the assistant model <x@example.com>") == [
        "attribution"
    ]


def test_ordinary_words_do_not_fail() -> None:
    for text in (
        "Generated with the --fix flag.",
        "A haiku is a poem.",
        "Fable about a sonnet.",
        "gemini is a zodiac sign",  # only the capitalised product name is a hit
        "A gpt partition table",
        "Co-Authored-By: Jay Wedgeworth <jay@example.com>",
        "",
    ):
        assert names_check(text) == [], text


def test_the_review_apps_pass() -> None:
    text = (
        "Augment finished its review. Codex found two issues.\n"
        "Reviewed by augmentcode[bot] and chatgpt-codex-connector[bot]."
    )
    assert names_check(text) == []
    for name in ALLOWED_NAMES:
        assert names_check(f"{name} reviewed it") == []


def test_an_allowed_name_does_not_hide_a_product_name_next_to_it() -> None:
    assert kinds("OpenAI Codex reviewed it") == ["agent_name"]
    assert kinds("Codex and Claude reviewed it") == ["agent_name"]


def test_the_repository_commit_trailer_passes_and_a_changed_one_does_not() -> None:
    assert ALLOWED_LINES == (TRAILER,)
    assert names_check(f"feat: x\n\n{TRAILER}\n") == []
    assert names_check(f"feat: x\n\n{TRAILER} extra") != []
    assert names_check("Co-Authored-By: Claude Opus <noreply@anthropic.com>") != []


@pytest.mark.parametrize(
    "text",
    [
        "The tier is `claude-gw-tier2` here.",
        "Run ``claude --model claude-gw-tier2`` first.",
        "Title: `Claude Code` hook fails, and `OpenAI` too.",
        'See [the plan](https://example.com/p "Claude Code plan") for it.',
        "See [the plan](https://example.com/p 'gpt-4 notes') for it.",
        '[plan]: https://example.com/p "Notes from Claude"',
    ],
)
def test_a_name_inside_a_backtick_span_or_a_link_title_passes(text: str) -> None:
    assert names_check(text) == []


def test_a_backtick_span_hides_only_its_own_text() -> None:
    assert kinds("`claude-gw-tier2` then claude-gw-tier2") == ["model_id"]
    assert names_check("`claude-gw-tier2` then claude-gw-tier2")[0].line == 1
    assert kinds("an open `tick and claude-gw-tier2") == [
        "model_id"
    ]  # no closing tick: no span


def test_a_link_text_is_scanned_and_only_its_title_is_skipped() -> None:
    assert kinds('[Claude Code notes](https://example.com "title")') == ["agent_name"]


@pytest.mark.parametrize("heading", QUOTED_HEADINGS)
def test_a_fence_headed_as_quoted_data_passes(heading: str) -> None:
    fence = "```\nthe worker said it is claude-gw-tier2 and Claude\n```"
    for head in (
        heading,
        heading.capitalize(),
        f"**{heading.capitalize()}:**",
        f"### {heading}:",
    ):
        assert names_check(f"{head}\n\n{fence}\n\nthen done") == [], head
        assert names_check(f"{head}\n{fence.replace('```', '~~~')}") == [], head


def test_a_fence_with_any_other_heading_or_none_is_scanned() -> None:
    body = "```\nclaude-gw-tier2\n```"
    assert kinds(f"Quoted from the compiler\n{body}") == ["model_id"]
    assert kinds(f"Some text\n{body}") == ["model_id"]
    assert kinds(body) == ["model_id"]
    # a quoted heading belongs to the next fence only
    assert kinds(f"Quoted from the issue\n```\nok\n```\nmore\n{body}") == ["model_id"]


def test_a_quoted_fence_that_is_never_closed_is_scanned() -> None:
    assert kinds("Quoted from the issue\n```\nclaude-gw-tier2\n") == ["model_id"]


def test_a_quoted_fence_skips_only_its_own_lines_and_reports_the_line_after_it() -> (
    None
):
    text = "Quoted from the worker\n```\nClaude\n```\nline five claude-gw-tier2"
    (hit,) = names_check(text)
    assert (hit.kind, hit.line) == ("model_id", 5)


def test_one_identifier_is_one_hit() -> None:
    assert [h.text for h in names_check("claude-gw-tier2 and gpt-4")] == [
        "claude-gw-tier2",
        "gpt-4",
    ]


def test_a_fake_launch_effective_string_is_caught_wherever_it_would_be_written() -> (
    None
):
    effective = "claude-gw-tier2-20261119"
    for template in (
        "Agent session: {} (tier2)",
        "- Worker started on {}.",
        "> {}",
    ):
        assert kinds(template.format(effective)) == ["model_id"]


def test_the_deny_list_is_data_with_the_three_kinds() -> None:
    assert {kind for kind, _ in DENY_PATTERNS} == {
        "model_id",
        "agent_name",
        "attribution",
    }
