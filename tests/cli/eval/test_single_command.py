"""FR-G6 single-command local runnability smoke test (T04.11 / D-0073).

The cliEval harness ships with a single-command contract: on a clean
Linux dev machine, ``make dev`` followed by

    uv run superclaude eval run --suite real --eval E1

MUST exit 0, write ``summary.md`` and ``summary.json`` into the per-run
output directory, and require no further manual setup. This module pins
that contract at the process boundary.

**Clean-host contract** (phase-4 §T04.11 AC):

* A fresh checkout + ``make dev`` is the only setup. No environment
  variables, no extra binaries beyond the ``required_binaries`` listed in
  the ``real`` suite manifest, no manual file editing.
* The invocation MUST be the literal command quoted in the AC; this test
  uses :func:`subprocess.run` against the installed ``superclaude``
  console-script so the test exercises the same entry point an operator
  would invoke.
* The per-run output directory is supplied via ``--output-dir`` (pointed
  at the AC12 ``/tmp/eval-runs`` allowlist) so the assertion does not
  have to recover an autogenerated run-id path from stdout. The same
  ``summary.{md,json}`` artifacts MUST appear regardless of whether
  ``--output-dir`` is supplied; pinning the path keeps the test
  hermetic.

**Pre-E1 / pre-T04.10-body behaviour:** the phase-4 tasklist Notes
record that ``E1 (T05.02) must exist for end-to-end validation; pre-E1
phase smoke uses a stub eval``. Until ``suites/real.yaml`` and the E1
spec land, the literal invocation cannot succeed (the suite resolver
exits 2 with ``SuiteNotFound``), and until T04.10's helper functions are
materialised the command crashes with ``NameError`` before reaching the
suite resolver. This test detects both preconditions and emits a clear
``pytest.skip`` with the missing-dependency reason so a sprint runner
sees a green skip rather than a red failure that does not reflect this
task's deliverable.
"""

from __future__ import annotations

import json
import os
import subprocess
import sys
from pathlib import Path

import pytest
import yaml

from superclaude.cli.eval.suites import SCHEMA_PATH

REAL_SUITE_PATH: Path = SCHEMA_PATH.parent / "real.yaml"
"""Filesystem location of the ``real`` suite manifest (lands in T05.01)."""


TARGET_EVAL_ID: str = "E1"
"""Eval id the AC pins as the one-eval smoke target (lands in T05.02)."""


SUMMARY_FILES: tuple[str, ...] = ("summary.md", "summary.json")
"""Per-run summary artifacts FR-G4 requires (T04.13 anchors the writer).

The AC for T04.11 names these two filenames verbatim; pinning them as a
tuple keeps the assertion loop readable while making it easy to extend
when FR-G4 grows additional summary surfaces (e.g. ``summary.yaml`` once
T04.13 lands).
"""


SUMMARY_JSON_RUN_DIR_KEY: str = "run_dir"
"""``summary.json`` key whose value is the per-run directory path.

Reserved for follow-up assertions once T04.13 (FR-G4 artifact layout)
lands the documented run-dir cross-link.
"""


# ---------------------------------------------------------------------------
# Pre-condition detection
# ---------------------------------------------------------------------------


def _missing_real_suite() -> bool:
    """Return True when ``suites/real.yaml`` is not on disk.

    The real-suite manifest lands in T05.01 (R-082+); until then the
    smoke test cannot run the literal AC invocation and must skip.
    """

    return not REAL_SUITE_PATH.is_file()


def _missing_target_eval() -> bool:
    """Return True when ``E1`` lacks an executable body in ``suites/real.yaml``.

    Even after T05.01 lands the manifest, the ``E1`` spec body lands in
    T05.02. Until then ``--eval E1`` resolves to a runner contract that
    cannot validate FR-G6.

    "Body present" is detected via the ``inputs`` field rather than the
    bare ``id`` because T04.16 (DOC-OQ3 / R-077) lands the exclusion-set
    scaffold for real.yaml (every E1-E15 entry annotated with
    ``no_pty: skip``) before the per-eval inputs/expects bodies land in
    T05.02. Without the inputs check, the smoke test would un-skip the
    moment T04.16 lands the scaffold and immediately fail because the
    runner has no prompt to drive Claude with. Anchoring on ``inputs``
    keeps the skip reason precise: present + executable, not just present.
    """

    if not REAL_SUITE_PATH.is_file():
        return True
    try:
        payload = yaml.safe_load(REAL_SUITE_PATH.read_text(encoding="utf-8"))
    except (OSError, yaml.YAMLError):
        return True
    if not isinstance(payload, dict):
        return True
    evals = payload.get("evals") or []
    if not isinstance(evals, list):
        return True
    for row in evals:
        if (
            isinstance(row, dict)
            and row.get("id") == TARGET_EVAL_ID
            and isinstance(row.get("inputs"), list)
            and row["inputs"]
        ):
            return False
    return True


def _eval_run_body_incomplete() -> bool:
    """Return True when T04.10's helper functions are still unwired.

    The phase-4 tasklist sequences T04.10 (FR-CLI1 ``eval run`` body)
    before T04.11 (this smoke test). The current ``commands.py``
    references helper functions (``_new_run_id``, ``_run_one_spec``,
    etc.) whose definitions land with T04.10's body; until those names
    resolve, the ``eval run`` invocation raises ``NameError`` long
    before it can produce a ``summary.{md,json}`` pair. Detecting this
    here keeps the skip reason precise and the failure mode green.
    """

    from superclaude.cli.eval import commands as cmds

    required_names = (
        "_new_run_id",
        "_default_output_dir",
        "_resolve_executor_factory",
        "_run_one_spec",
        "_utc_iso_now",
        "_compute_run_stats",
        "_format_run_summary_line",
        "_can_install_signal_handler",
        "RUN_CLEAN_EXIT_CODE",
        "RUN_FAILURES_EXIT_CODE",
        "RUN_INTERRUPTED_EXIT_CODE",
    )
    return any(not hasattr(cmds, name) for name in required_names)


_SKIP_REASONS: tuple[tuple[str, "callable[[], bool]"], ...] = (
    (
        "T05.01 deliverable suites/real.yaml not yet on disk; "
        "pre-real-suite smoke is deferred (see phase-4-tasklist.md §T04.11 Notes).",
        _missing_real_suite,
    ),
    (
        "T05.02 deliverable eval E1 not yet present in suites/real.yaml; "
        "pre-E1 phase smoke uses a stub eval (see phase-4-tasklist.md §T04.11 Notes).",
        _missing_target_eval,
    ),
    (
        "T04.10 FR-CLI1 ``eval run`` body helpers not yet defined in "
        "src/superclaude/cli/eval/commands.py; running the literal invocation "
        "would crash with NameError. T04.11 smoke unblocks once T04.10 lands.",
        _eval_run_body_incomplete,
    ),
)


def _resolve_skip_reason() -> str | None:
    """Return the first matching skip reason, or ``None`` to run the test."""

    for reason, predicate in _SKIP_REASONS:
        try:
            if predicate():
                return reason
        except Exception as exc:  # noqa: BLE001 — defensive
            return f"precondition probe raised {type(exc).__name__}: {exc}"
    return None


