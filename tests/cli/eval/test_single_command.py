def test_single_command_local_runnability(tmp_path: Path) -> None:
    """``uv run superclaude eval run --suite real --eval E1`` exits 0.

    Asserts the FR-G6 contract end-to-end:

    1. The literal AC invocation completes with process exit code ``0``.
    2. ``summary.md`` and ``summary.json`` appear under the per-run
       directory (here pinned via ``--output-dir`` for hermeticity).
    3. ``summary.json`` parses as a JSON object — a deterministic
       schema check is owned by TEST-007 (T04.17); this test merely
       confirms the file is non-empty and well-formed at the process
       boundary.

    Skipped (with a precise reason) when any of the documented
    upstream dependencies are unmet — see :func:`_resolve_skip_reason`.
    """

    skip_reason = _resolve_skip_reason()
    if skip_reason is not None:
        pytest.skip(skip_reason)

    # AC12 scratch-root allowlist: ``/tmp/eval-runs`` is the canonical
    # tmp-prefixed root. Use a unique subdirectory so parallel pytest
    # invocations cannot collide on the same per-run tree.
    output_dir = Path("/tmp/eval-runs") / f"t04_11_{os.getpid()}_{id(tmp_path):x}"
    output_dir.mkdir(parents=True, exist_ok=True)

    cmd = [
        "uv",
        "run",
        "superclaude",
        "eval",
        "run",
        "--suite",
        "real",
        "--eval",
        TARGET_EVAL_ID,
        "--output-dir",
        str(output_dir),
    ]

    completed = subprocess.run(
        cmd,
        check=False,
        capture_output=True,
        text=True,
        cwd=Path(__file__).resolve().parents[3],
        timeout=600,
    )

    assert completed.returncode == 0, (
        f"FR-G6 smoke failed: exit={completed.returncode}\n"
        f"stdout:\n{completed.stdout}\n"
        f"stderr:\n{completed.stderr}"
    )

    # H1: artifacts land under the compose_run_dir-derived run-dir
    # (output_dir is the OUTPUT ROOT; the FR-G4 run-dir is at
    # ``<output_dir>/.dev/eval-runs/<YYYY-MM-DD>/<run-id>/``).
    eval_runs_root = output_dir / ".dev" / "eval-runs"
    assert eval_runs_root.is_dir(), (
        f"FR-G4 layout root missing: {eval_runs_root}\n"
        f"stdout:\n{completed.stdout}\nstderr:\n{completed.stderr}"
    )
    date_dirs = sorted(p for p in eval_runs_root.iterdir() if p.is_dir())
    assert len(date_dirs) == 1
    run_dirs = sorted(p for p in date_dirs[0].iterdir() if p.is_dir())
    assert len(run_dirs) == 1
    per_run_dir = run_dirs[0]

    for filename in SUMMARY_FILES:
        artifact = per_run_dir / filename
        assert artifact.is_file(), (
            f"FR-G6 AC: {filename!r} missing under per-run dir "
            f"{per_run_dir}; stdout:\n{completed.stdout}\n"
            f"stderr:\n{completed.stderr}"
        )
        assert artifact.stat().st_size > 0, (
            f"FR-G6 AC: {filename!r} present but empty under {per_run_dir}."
        )

    summary_json = per_run_dir / "summary.json"
    payload = json.loads(summary_json.read_text(encoding="utf-8"))
    assert isinstance(payload, dict), (
        f"FR-G6 AC: summary.json should be a JSON object; got "
        f"{type(payload).__name__}."
    )


def test_single_command_contract_is_documented() -> None:
    """Guard: this module's docstring records the clean-host contract.

    The phase-4 tasklist AC requires the test file to document the
    ``no manual setup beyond `make dev``` contract. Pinning that
    sentence as a module-level assertion stops a future docstring
    rewrite from silently dropping the contract record.
    """

    module_doc = sys.modules[__name__].__doc__ or ""
    assert "make dev" in module_doc, (
        "T04.11 AC: test module docstring must record the clean-host "
        "contract (only ``make dev`` setup required); current docstring "
        "does not mention ``make dev``."
    )
    assert "summary.md" in module_doc and "summary.json" in module_doc, (
        "T04.11 AC: test module docstring must name the summary "
        "artifacts the smoke test asserts on."
    )
