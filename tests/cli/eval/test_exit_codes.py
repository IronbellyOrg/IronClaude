# Exit code 2 — harness contract error
# ---------------------------------------------------------------------------


def test_exit_code_2_harness_error(tmp_path: Path) -> None:
    """Invalid flags trigger ``HARD_FAIL_EXIT_CODE`` (= 2).

    Pins the contract through two independent harness-error gates so
    the exit-code-2 surface is verified from more than one entry
    point:

    1. ``--timeout-mult 0`` — flag validation at
       ``commands.py:1398`` raises ``HARD_FAIL_EXIT_CODE``.
    2. ``--max-disk-mb -1`` — flag validation at
       ``commands.py:1405`` raises ``HARD_FAIL_EXIT_CODE``.

    Both gates run BEFORE the run-loop closure, so this test is
    independent of T04.10 and runs today.

    The test also asserts the harness's exit-code-2 constant equals
    ``2`` at the library boundary; together with the process-level
    assertion that guards against the constant drifting away from the
    contract that operators and CI consume.
    """

    from superclaude.cli.eval.commands import HARD_FAIL_EXIT_CODE

    # Library-boundary constant pin — guards against the constant
    # drifting silently away from design-spec §4.
    assert HARD_FAIL_EXIT_CODE == 2, (
        f"HARD_FAIL_EXIT_CODE must equal 2 per design-spec §4, "
        f"got {HARD_FAIL_EXIT_CODE}"
    )

    output_dir = tmp_path / "run"

    # Gate 1 — --timeout-mult must be > 0.
    timeout_result = _run_eval(
        "--suite",
        "real",
        "--no-pty",
        "--timeout-mult",
        "0",
        "--output-dir",
        str(output_dir / "tm"),
    )
    assert timeout_result.returncode == 2, (
        "invalid --timeout-mult must exit 2 (HARD_FAIL_EXIT_CODE); "
        f"got {timeout_result.returncode}\n"
        f"--- stdout ---\n{timeout_result.stdout}\n"
        f"--- stderr ---\n{timeout_result.stderr}"
    )
    assert "--timeout-mult" in timeout_result.stderr, (
        "stderr must surface the validated flag name "
        f"(--timeout-mult); got:\n{timeout_result.stderr}"
    )

    # Gate 2 — --max-disk-mb must be >= 0.
    disk_result = _run_eval(
        "--suite",
        "real",
        "--no-pty",
        "--max-disk-mb",
        "-1",
        "--output-dir",
        str(output_dir / "mdmb"),
    )
    assert disk_result.returncode == 2, (
        "invalid --max-disk-mb must exit 2 (HARD_FAIL_EXIT_CODE); "
        f"got {disk_result.returncode}\n"
        f"--- stdout ---\n{disk_result.stdout}\n"
        f"--- stderr ---\n{disk_result.stderr}"
    )
    assert "--max-disk-mb" in disk_result.stderr, (
        "stderr must surface the validated flag name "
        f"(--max-disk-mb); got:\n{disk_result.stderr}"
    )


