"""TEST-008 — process-boundary exit-code semantics for ``superclaude eval run``.

T04.19 / D-0079 — pins the four exit codes named in design-spec §4 at the
**process boundary** (via ``subprocess.run`` + ``returncode``), the
single surface every operator, CI job, and downstream pipeline reads.

The four exit codes (design-spec §4):

* ``0`` — clean: every expanded eval reached PASS / SKIPPED / XFAIL and
  no breach occurred.
* ``1`` — failing run: at least one eval ended FAIL / ERRORED / TIMEOUT
  / XPASS but the harness itself ran to completion.
* ``2`` — harness contract error: invalid flag, scratch-root violation,
  suite-not-found, disk-budget exceeded, Reporter contract violation,
  capability gate breach, etc. The harness rejected the run before /
  during dispatch.
* ``3`` — interrupted: SIGINT / SIGTERM landed mid-run and the
  cooperative cancellation path drained.

Sibling tests:

* :mod:`tests.cli.eval.test_reporter_contract` (T04.17) pins the same
  exit-code-2 contract at the *library* boundary
  (``REPORTER_CONTRACT_VIOLATION_EXIT_CODE`` constant + exception
  type). This module pins the same number through the process boundary
  so the constant cannot drift without breaking the operator-visible
  surface.

Forward-compat:

The exit-code-2 paths (``--timeout-mult <=0``, ``--max-disk-mb <0``)
are guarded by flag validation that runs BEFORE the
:mod:`superclaude.cli.eval.commands` run-id helper, so they exercise
real ``sys.exit(HARD_FAIL_EXIT_CODE)`` calls today. The 0 / 1 / 3 paths
all flow through the run-loop closure whose helpers (``_new_run_id``,
``_run_one_spec``, ``_compute_run_stats``, ``RUN_CLEAN_EXIT_CODE``,
``RUN_FAILURES_EXIT_CODE``, ``RUN_INTERRUPTED_EXIT_CODE``) are T04.10
deliverables. While those helpers are absent we ``pytest.skip`` those
three tests with a self-clearing diagnostic; the skips evaporate once
T04.10 lands, so the suite then pins all four codes end-to-end.

The exit-code-2 test always runs because its contract is the one this
release can prove today and is the one the Reporter / Capability /
Suite-loader contracts already lean on.
"""

from __future__ import annotations

import os
import signal
import subprocess
import sys
import time
from pathlib import Path

import pytest


REPO_ROOT = Path(__file__).resolve().parents[3]


def _resolve_superclaude_bin() -> str:
    """Locate the ``superclaude`` console-script in the active venv.

    The package has no ``__main__.py``, so ``python -m superclaude``
    fails. The console-script entry generated by hatchling is the
    canonical operator surface — and is exactly what CI / docs tell
    users to invoke.
    """

    venv_bin = Path(sys.executable).parent / "superclaude"
    if venv_bin.exists():
        return str(venv_bin)
    import shutil

    path_bin = shutil.which("superclaude")
    if path_bin:
        return path_bin
    pytest.skip(
        "superclaude console-script not found on this environment; "
        "exit-code tests need the operator-visible CLI shim."
    )


SUPERCLAUDE_BIN = _resolve_superclaude_bin()


# ---------------------------------------------------------------------------
# Forward-dependency probe (T04.10 helpers)
# ---------------------------------------------------------------------------


def _t0410_missing() -> list[str]:
    """Return the names of T04.10 run-loop deliverables not yet defined.

    Tests for exit codes 0, 1, and 3 traverse the run-loop closure;
    that closure references helpers defined in T04.10. When any of
    them are missing the closure raises ``NameError`` before reaching
    the exit-code branch, so we skip those tests with a diagnostic
    that auto-clears once the helpers land.
    """

    from superclaude.cli.eval import commands as _commands_mod

    forward_deps = (
        "_new_run_id",
        "_run_one_spec",
        "_compute_run_stats",
        "RUN_CLEAN_EXIT_CODE",
        "RUN_FAILURES_EXIT_CODE",
        "RUN_INTERRUPTED_EXIT_CODE",
    )
    return [n for n in forward_deps if not hasattr(_commands_mod, n)]


def _skip_unless_t0410_landed() -> None:
    missing = _t0410_missing()
    if missing:
        pytest.skip(
            f"T04.10 forward dependency not yet landed: {missing!r}. "
            "The exit-code-2 path pinned below runs today; the 0 / 1 / 3 "
            "paths un-skip automatically once T04.10 wires the run-loop "
            "closure helpers."
        )


# ---------------------------------------------------------------------------
# subprocess helper
# ---------------------------------------------------------------------------


def _run_eval(
    *args: str,
    timeout: float = 60.0,
    env: dict[str, str] | None = None,
) -> subprocess.CompletedProcess[str]:
    """Invoke ``superclaude eval run ...`` as a real subprocess.

    Uses ``sys.executable -m superclaude`` to avoid depending on the
    PATH-installed shim, matching how CI pipelines run the harness.
    Captures stdout + stderr and returns the completed process so the
    caller can assert on both the exit code and the surfaced
    diagnostic.
    """

    cmd = [SUPERCLAUDE_BIN, "eval", "run", *args]
    merged_env = dict(os.environ)
    if env:
        merged_env.update(env)
    return subprocess.run(
        cmd,
        capture_output=True,
        text=True,
        cwd=str(REPO_ROOT),
        env=merged_env,
        timeout=timeout,
        check=False,
    )


# ---------------------------------------------------------------------------
# Exit code 0 — clean run
# ---------------------------------------------------------------------------


def test_exit_code_0_clean_run(allowlisted_output_dir: Path) -> None:
    """``--suite real --no-pty`` skips every E1-E15 → clean exit 0.

    The DOC-OQ3 / D-0077 exclusion set tags every eval in ``real.yaml``
    ``no_pty: skip``. With ``--no-pty`` on the CLI the orchestrator
    short-circuits the whole suite into SKIPPED outcomes — no failures,
    no breaches, so design-spec §4 lands at exit ``0``.

    Skipped until T04.10 wires the run-loop closure (see module
    docstring).
    """

    _skip_unless_t0410_landed()

    output_dir = allowlisted_output_dir / "run"
    result = _run_eval(
        "--suite",
        "real",
        "--no-pty",
        "--output-dir",
        str(output_dir),
    )

    assert result.returncode == 0, (
        f"clean run must exit 0, got {result.returncode}\n"
        f"--- stdout ---\n{result.stdout}\n--- stderr ---\n{result.stderr}"
    )


