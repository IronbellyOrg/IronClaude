# Exit code 1 — failing run
# ---------------------------------------------------------------------------


def test_exit_code_1_failing_run(tmp_path: Path) -> None:
    """A run with at least one FAIL outcome exits 1.

    Authored against a synthetic single-eval suite whose body is wired
    to fail its ``expects`` block. Since the body wiring depends on
    T04.10's ``_run_one_spec`` we skip until that helper lands; the
    library-level FAIL → exit-1 mapping is already pinned by the
    Reporter and run-report contract tests.

    When T04.10 lands this test will:

    1. Materialise a tmp suite with one spec that fails by construction.
    2. Run ``superclaude eval run --suite <tmp> --no-pty`` (or with the
       synthetic body inline).
    3. Assert ``returncode == 1`` and the summary records the failure.
    """

    _skip_unless_t0410_landed()

    # The synthetic-fail path additionally needs the M5 expects-resolver
    # that translates manifest ``expects:`` rows into ``ExpectCallable``s.
    # Until that lands, ``_run_one_spec`` ships with ``expect_callables=()``
    # and every non-PTY-skipped spec returns PASS.
    from superclaude.cli.eval import commands as _commands_mod

    if not hasattr(_commands_mod, "_build_expects_from_spec"):
        pytest.skip(
            "M5 expects-resolver (_build_expects_from_spec) not yet "
            "landed; _run_one_spec ships with expect_callables=() so "
            "this test cannot exercise the FAIL path. Un-skips when the "
            "resolver lands."
        )

    # Synthetic single-eval suite that fails by construction. We rely
    # on a deliberately mismatched ``expect:`` so the run finishes
    # cleanly with one FAIL outcome rather than a harness breach.
    suite_dir = tmp_path / "suite"
    suite_dir.mkdir(parents=True)
    suite_path = suite_dir / "fail.yaml"
    suite_path.write_text(
        "name: fail\n"
        "version: '1.0'\n"
        "description: 'one-eval suite that fails by construction'\n"
        "defaults:\n"
        "  per_eval_timeout_sec: 30\n"
        "  per_eval_memory_mb: 256\n"
        "  capture_tty: false\n"
        "evals:\n"
        "  - id: F1\n"
        "    title: 'fail by construction'\n"
        "    category: synthetic\n"
        "    timeout_sec: 30\n"
        "    isolation:\n"
        "      home_strategy: ephemeral\n"
        "    inputs: []\n"
        "    expects:\n"
        "      - kind: exit_code\n"
        "        value: 9999\n"
    )

    output_dir = tmp_path / "run"
    result = _run_eval(
        "--suite",
        str(suite_path),
        "--no-pty",
        "--output-dir",
        str(output_dir),
    )

    # `--no-pty` may short-circuit a tagged suite to SKIPPED. Without
    # ``no_pty: skip`` on the spec the runner enters the FAIL path and
    # the suite returns 1.
    assert result.returncode == 1, (
        f"failing run must exit 1, got {result.returncode}\n"
        f"--- stdout ---\n{result.stdout}\n--- stderr ---\n{result.stderr}"
    )


