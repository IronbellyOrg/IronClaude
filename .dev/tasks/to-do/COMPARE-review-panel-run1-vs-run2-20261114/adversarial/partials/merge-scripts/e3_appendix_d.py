def short(text: str, limit: int = 220) -> str:
    if len(text) <= limit:
        return text
    cut = text.rfind(" ", 0, limit)
    text = text[:cut].rstrip(" ,;:(")
    if text.count("`") % 2:
        text += "`"
    if text.count("(") > text.count(")"):
        text += ")" * (text.count("(") - text.count(")"))
    return text + " …"


