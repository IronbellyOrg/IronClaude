#!/usr/bin/env python3
"""Merge executor E3: generate Appendix D (compare-debate invariant probe, M-29 of refactor-plan.md).

Reads (read-only): invariant-probe.md (32 rows). Writes the Appendix D part of
partials/merge-stage/new-blocks/M29-appendices-D-E.md; everything after the marker
line `<!-- APPENDIX-E -->` in an existing file is kept unchanged.
Run: uv run --no-project python e3_appendix_d.py
The "Carried in this document" column is a hand-kept map (CARRY) from refactor-plan.md M-00..M-29.
"""
from __future__ import annotations

import re
from pathlib import Path

ADV = Path(__file__).resolve().parents[2]
PROBE = (ADV / "invariant-probe.md").read_text(encoding="utf-8").split("\n")
OUT = ADV / "partials" / "merge-stage" / "new-blocks" / "M29-appendices-D-E.md"
MARK = "<!-- APPENDIX-E -->"


def cells(line: str) -> list[str]:
    return [p.strip() for p in re.split(r"(?<!\\)\|", line.strip())[1:-1]]


rows = []
for ln in PROBE:
    if re.match(r"^\| INV-\d{3} ", ln):
        c = cells(ln)
        assert len(c) == 6, (c[0], len(c))
        rows.append(c)
assert len(rows) == 32 and [r[0] for r in rows] == [f"INV-{i:03d}" for i in range(1, 33)]

